// Purpose: ClipboardHistory, the last 20 texts and images copied anywhere on this Mac (screenshots
//          sent to the clipboard included), for the companion card's Clipboard list (copy one
//          again, or insert it at the cursor).
// Dependencies: AppKit (NSPasteboard), ImageIO (thumbnails)
// Used by: Sources/App/ViewModels/AppViewModel.swift (owns it, starts it at launch),
//          Sources/App/Supporting/MeetingPillController.swift (MeetingPillModel.clipboardSource),
//          Sources/App/Views/MeetingPillView.swift (the Clipboard list in the companion card)
// Notes: - macOS has no clipboard notification, so the pasteboard's changeCount is polled every
//          0.5 s; reading an integer is cheap, the string is read only when it changed.
//        - Kept in memory only, never written to disk: copied text can be anything, and a file of
//          it would outlive the moment. The list starts empty on every launch.
//        - Skips what password managers and other apps mark as secret or temporary
//          (nspasteboard.org types; 1Password and others set them), whitespace-only text, and
//          MinuteMind's own short-lived paste buffer (TextInsertionService marks it transient).
//        - Copying a text or image that is already listed moves it to the top instead of
//          repeating it.
//        - Text wins when the pasteboard has both (a copied file name, a web page selection);
//          an image is kept as the exact PNG or TIFF bytes it came as, so copying it back loses
//          nothing, plus a small thumbnail for the row. Images over 50 MB are not kept.

import AppKit
import ImageIO

@MainActor
@Observable
final class ClipboardHistory {
    struct Item: Identifiable, Equatable {
        enum Content {
            case text(String)
            case image(Image)
        }

        let id = UUID()
        let content: Content
        let copiedAt: Date

        var text: String? {
            if case .text(let text) = content { return text }
            return nil
        }

        /// The row's one line: the text, or "Image 1920 × 1080".
        var title: String {
            switch content {
            case .text(let text): return ClipboardHistory.preview(text)
            case .image(let image): return "Image \(image.pixelWidth) \u{00D7} \(image.pixelHeight)"
            }
        }

        static func == (lhs: Item, rhs: Item) -> Bool { lhs.id == rhs.id }
    }

    /// A copied image: its original bytes and type, and a thumbnail for the list.
    struct Image {
        let data: Data
        let type: NSPasteboard.PasteboardType
        let pixelWidth: Int
        let pixelHeight: Int
        let thumbnail: NSImage

        /// Reads PNG or TIFF bytes; nil when they are not a decodable image.
        init?(data: Data, type: NSPasteboard.PasteboardType) {
            guard let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? Int,
                  let height = properties[kCGImagePropertyPixelHeight] as? Int,
                  let thumb = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                      kCGImageSourceCreateThumbnailFromImageAlways: true,
                      kCGImageSourceCreateThumbnailWithTransform: true,
                      kCGImageSourceThumbnailMaxPixelSize: 96,
                  ] as CFDictionary)
            else { return nil }
            self.data = data
            self.type = type
            pixelWidth = width
            pixelHeight = height
            thumbnail = NSImage(cgImage: thumb, size: NSSize(width: thumb.width, height: thumb.height))
        }
    }

    static let limit = 20
    /// Longer copies are listed, but only this much is kept, so the list stays light.
    static let maxLength = 100_000
    static let maxImageBytes = 50_000_000

    /// Pasteboard types that mean "do not remember this" (nspasteboard.org conventions).
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Newest first.
    private(set) var items: [Item] = []

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        if let text = pasteboard.string(forType: .string) {
            record(text)
        } else if let type = pasteboard.availableType(from: [.png, .tiff]),
                  let data = pasteboard.data(forType: type), data.count <= Self.maxImageBytes,
                  let image = Image(data: data, type: type) {
            record(image)
        }
    }

    /// Adds a copied text at the top (or moves it there when already listed).
    func record(_ text: String, at date: Date = Date()) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let kept = String(text.prefix(Self.maxLength))
        items.removeAll { $0.text == kept }
        insert(Item(content: .text(kept), copiedAt: date))
    }

    /// Adds a copied image at the top (or moves it there when already listed).
    func record(_ image: Image, at date: Date = Date()) {
        items.removeAll {
            if case .image(let listed) = $0.content { return listed.data == image.data }
            return false
        }
        insert(Item(content: .image(image), copiedAt: date))
    }

    private func insert(_ item: Item) {
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Puts a listed entry back on the clipboard (the next poll moves it to the top).
    static func copy(_ item: Item) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.setData(image.data, forType: image.type)
        }
    }

    /// One line for the list: whitespace runs collapsed, so multi-line copies read as one row.
    nonisolated static func preview(_ text: String) -> String {
        text.prefix(300).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }
}
